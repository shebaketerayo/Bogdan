import os

HERE = os.path.dirname(os.path.abspath(__file__))
FRAMES_TXT = os.path.join(HERE, 'build', 'frames.txt')
ICON_TXT = os.path.join(HERE, 'icon.txt')
OUT = os.path.join(HERE, '..', '..', 'src', 'SpriteArt.cs')
W, H = 48, 40

frames, anims = [], []
cur = None
with open(FRAMES_TXT, encoding='utf-8') as f:
    for raw in f:
        line = raw.rstrip('\n').rstrip('\r')
        if line.startswith('@'):
            cur = [line[1:], []]
            frames.append(cur)
        elif line.startswith('!'):
            anims.append(line[1:].strip())
            cur = None
        elif line.strip() and cur is not None:
            cur[1].append(line)

with open(ICON_TXT, encoding='utf-8') as f:
    icon = [r.rstrip() for r in f.read().strip('\n').split('\n')]

out = []
out.append('// generated by tools/sprites/gen_cs.py, edit the art there')
out.append('namespace DesktopCat')
out.append('{')
out.append('    internal static class SpriteArt')
out.append('    {')
out.append('        public const int Width = %d;' % W)
out.append('        public const int Height = %d;' % H)
out.append('')
out.append('        public const string Anims = @"')
out.extend(anims)
out.append('";')
out.append('')
out.append('        public const string Icon16 = @"')
out.extend(icon)
out.append('";')
out.append('')
out.append('        public const string Frames = @"')
for hdr, rows in frames:
    assert len(rows) == H, hdr
    for r in rows: assert len(r) == W, (hdr, r)
    k = 0
    while k < H - 1 and rows[k].strip('.') == '': k += 1
    out.append('@' + hdr)
    out.extend(rows[k:])
out.append('";')
out.append('    }')
out.append('}')
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('\n'.join(out) + '\n')
print('SpriteArt.cs:', len(frames), 'frames,', len(anims), 'anims')
